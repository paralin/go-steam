package main

import (
	"bytes"
	"fmt"
	"go/constant"
	"go/format"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// languageTypes maps fixed-width wire scalars to their Go representations.
var languageTypes = map[string]string{
	"byte": "uint8", "short": "int16", "ushort": "uint16", "int": "int32",
	"uint": "uint32", "long": "int64", "ulong": "uint64", "char": "uint16",
}

// languageConstants resolves aliases while retaining arbitrary-width integers.
type languageConstants struct {
	// expressions maps qualified constant names to their operands.
	expressions map[string][]string
	// values caches evaluated constants.
	values map[string]constant.Value
	// visiting detects recursive aliases.
	visiting map[string]bool
}

// generateSteamLanguage writes both generated files from the retained definitions.
func generateSteamLanguage(repoRoot string) error {
	// Validate and format both outputs before replacing either retained file.
	decls, err := parseLanguage(filepath.Join(repoRoot, "generator", "steamlang", "steammsg.steamd"))
	if err != nil {
		return err
	}
	enums, err := emitLanguageEnums(decls)
	if err != nil {
		return err
	}
	messages, err := emitLanguageMessages(decls)
	if err != nil {
		return err
	}

	// Publish the two generated files with ordinary source-file permissions.
	for _, output := range []struct {
		// name is relative to the generated SteamLanguage package.
		name string
		// data is the formatted Go source.
		data []byte
	}{{"enums.go", enums}, {"messages.go", messages}} {
		path := filepath.Join(repoRoot, "protocol", "steamlang", output.name)
		if err := os.WriteFile(path, output.data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

// emitLanguageEnums preserves enum constants and emits readable String methods.
func emitLanguageEnums(decls []languageDecl) ([]byte, error) {
	// Index constants before resolving aliases, including forward references.
	constants := languageConstants{
		expressions: make(map[string][]string),
		values:      make(map[string]constant.Value),
		visiting:    make(map[string]bool),
	}
	for _, decl := range decls {
		for _, field := range decl.fields {
			if decl.kind == "enum" || field.flag == "const" {
				constants.expressions[decl.name+"::"+field.name] = field.values
			}
		}
	}

	// Emit the package and declarations in their retained source order.
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./generator steamlang; DO NOT EDIT.\n\npackage steamlang\n\n")
	out.WriteString("import (\"sort\"; \"strconv\"; \"strings\")\n\n")
	for _, decl := range decls {
		if decl.kind != "enum" {
			continue
		}

		// Preserve each enum's public type and symbolic constant expressions.
		typ := "int32"
		if decl.option != "" {
			typ = languageType(decl.option)
		}
		fmt.Fprintf(&out, "// %s is a Steam protocol enumeration.\ntype %s %s\n\nconst (\n", decl.name, decl.name, typ)
		for _, field := range decl.fields {
			if field.obsolete != "" {
				fmt.Fprintf(&out, "// Deprecated: %s\n", field.obsolete)
			}
			fmt.Fprintf(&out, "%s_%s %s = %s\n", decl.name, field.name, decl.name, languageExpression(decl, field.values))
		}
		fmt.Fprintf(&out, ")\n\n// %s_name maps each value to its first declared name.\nvar %s_name = map[%s]string{\n", decl.name, decl.name, decl.name)

		// Use the first name for equal-valued aliases in the reverse lookup.
		seen := make(map[string]bool)
		for _, field := range decl.fields {
			value, err := constants.evaluate(decl.name + "::" + field.name)
			if err != nil {
				return nil, err
			}
			key := value.ExactString()
			if !seen[key] {
				seen[key] = true
				fmt.Fprintf(&out, "%s: %q,\n", key, decl.name+"_"+field.name)
			}
		}
		out.WriteString("}\n\n")
		emitLanguageStringer(&out, decl, typ)
	}
	return format.Source(out.Bytes())
}

// evaluate resolves numeric literals, aliases, and bitwise-OR combinations.
func (c *languageConstants) evaluate(name string) (constant.Value, error) {
	// Reuse completed values and reject references that cannot terminate.
	if value, ok := c.values[name]; ok {
		return value, nil
	}
	operands, ok := c.expressions[name]
	if !ok || len(operands) == 0 {
		return nil, fmt.Errorf("unknown or empty SteamLanguage constant %q", name)
	}
	if c.visiting[name] {
		return nil, fmt.Errorf("cyclic SteamLanguage constant %q", name)
	}
	c.visiting[name] = true
	defer delete(c.visiting, name)

	// Resolve scoped aliases and combine arbitrary-width integer operands.
	value := constant.MakeInt64(0)
	for _, operand := range operands {
		part := constant.MakeFromLiteral(operand, token.INT, 0)
		if part.Kind() == constant.Unknown {
			if !strings.Contains(operand, "::") {
				owner, _, _ := strings.Cut(name, "::")
				operand = owner + "::" + operand
			}
			var err error
			part, err = c.evaluate(operand)
			if err != nil {
				return nil, err
			}
		}
		value = constant.BinaryOp(value, token.OR, part)
	}
	c.values[name] = value
	return value, nil
}

// emitLanguageStringer treats only declared flag enums as bit fields.
func emitLanguageStringer(out *bytes.Buffer, decl languageDecl, typ string) {
	// Prefer the canonical declared name before interpreting flag combinations.
	fmt.Fprintf(out, "// String returns the declared name or the numeric value.\nfunc (e %s) String() string {\n", decl.name)
	fmt.Fprintf(out, "if name, ok := %s_name[e]; ok { return name }\n\n", decl.name)
	if decl.flags {
		out.WriteString("var names []string\nremaining := e\n")
		fmt.Fprintf(out, "for flag, name := range %s_name {\n", decl.name)
		out.WriteString("if flag != 0 && e & flag == flag { names = append(names, name); remaining &^= flag }\n}\n")
		out.WriteString("if remaining == 0 && len(names) > 0 { sort.Strings(names); return strings.Join(names, \" | \") }\n\n")
	}
	// Preserve unknown values numerically, including unsigned high bits.
	if strings.HasPrefix(typ, "uint") {
		out.WriteString("return strconv.FormatUint(uint64(e), 10)\n}\n\n")
	} else {
		out.WriteString("return strconv.FormatInt(int64(e), 10)\n}\n\n")
	}
}

// languageExpression translates scoped symbols without losing enum aliases.
func languageExpression(decl languageDecl, values []string) string {
	parts := make([]string, len(values))
	for i, value := range values {
		if value == "ulong.MaxValue" {
			parts[i] = "^uint64(0)"
			continue
		}

		// Qualify local aliases and translate explicitly scoped identifiers.
		parts[i] = strings.ReplaceAll(value, "::", "_")
		for _, field := range decl.fields {
			if value == field.name {
				parts[i] = decl.name + "_" + value
				break
			}
		}
	}
	return strings.Join(parts, " | ")
}

// languageType translates scalar storage and retained protobuf namespace names.
func languageType(name string) string {
	if typ, ok := languageTypes[name]; ok {
		return typ
	}
	if strings.HasPrefix(name, "SteamKit2.") {
		return "protobuf." + name[strings.LastIndexByte(name, '.')+1:]
	}
	return name
}

// fieldName exports a source member while preserving its existing initialisms.
func fieldName(name string) string {
	return strings.ToUpper(name[:1]) + name[1:]
}

// fieldType chooses the published representation of one binary field.
func fieldType(field languageField) string {
	switch field.flag {
	case "steamidmarshal":
		return "SteamId"
	case "boolmarshal":
		return "bool"
	case "proto":
		return "*" + languageType(field.typ)
	}
	if field.option != "" {
		return "[]" + languageType(field.typ)
	}
	return languageType(field.typ)
}

// emitLanguageMessages emits fixed-width wire codecs for every retained class.
func emitLanguageMessages(decls []languageDecl) ([]byte, error) {
	// Import the wire primitives used by the retained message definitions.
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./generator steamlang; DO NOT EDIT.\n\npackage steamlang\n\n")
	out.WriteString("import (\"encoding/binary\"; \"errors\"; \"io\"; \"github.com/paralin/go-steam/protocol/protobuf\")\n\n")
	out.WriteString("// SteamId is the wire representation of a Steam account identifier.\ntype SteamId uint64\n\n")
	for _, decl := range decls {
		if decl.kind != "class" {
			continue
		}

		// Emit constants and public fields before their constructor and wire methods.
		for _, field := range decl.fields {
			if field.flag == "const" {
				fmt.Fprintf(&out, "const %s_%s %s = %s\n\n", decl.name, field.name, languageType(field.typ), languageExpression(decl, field.values))
			}
		}
		fmt.Fprintf(&out, "// %s is an ordered Steam binary message.\ntype %s struct {\n", decl.name, decl.name)
		for _, field := range decl.fields {
			if field.flag != "const" {
				fmt.Fprintf(&out, "%s %s\n", fieldName(field.name), fieldType(field))
			}
		}
		out.WriteString("}\n\n")
		emitLanguageConstructor(&out, decl)
		if strings.HasPrefix(decl.option, "EMsg::") {
			fmt.Fprintf(&out, "// GetEMsg identifies the message body.\nfunc (d *%s) GetEMsg() EMsg { return %s }\n\n", decl.name, languageExpression(decl, []string{decl.option}))
		}
		if err := emitLanguageCodec(&out, decl, true); err != nil {
			return nil, err
		}
		if err := emitLanguageCodec(&out, decl, false); err != nil {
			return nil, err
		}
	}
	return format.Source(out.Bytes())
}

// emitLanguageConstructor initializes wire defaults and owned message buffers.
func emitLanguageConstructor(out *bytes.Buffer, decl languageDecl) {
	fmt.Fprintf(out, "// New%s initializes the protocol defaults.\nfunc New%s() *%s {\nreturn &%s{\n", decl.name, decl.name, decl.name, decl.name)
	for _, field := range decl.fields {
		if field.flag == "const" {
			continue
		}

		// Allocate message-owned buffers and apply the source defaults.
		value := languageExpression(decl, field.values)
		if field.flag == "proto" {
			value = "new(" + languageType(field.typ) + ")"
		} else if field.option != "" {
			value = "make(" + fieldType(field) + ", " + field.option + ")"
		}
		if value != "" {
			fmt.Fprintf(out, "%s: %s,\n", fieldName(field.name), value)
		}
	}
	out.WriteString("}\n}\n\n")
}

// emitLanguageCodec reads or writes fields in schema order, including framing.
func emitLanguageCodec(out *bytes.Buffer, decl languageDecl, writing bool) error {
	// Prepare protobuf payloads before writing their length-prefixed headers.
	if writing {
		fmt.Fprintf(out, "// Serialize writes the complete binary message.\nfunc (d *%s) Serialize(w io.Writer) error {\n", decl.name)
		for _, field := range decl.fields {
			if field.flag == "proto" {
				name := fieldName(field.name)
				fmt.Fprintf(out, "%sBytes, err := d.%s.MarshalVT()\nif err != nil { return err }\n", name, name)
				fmt.Fprintf(out, "d.%s = int32(len(%sBytes))\n\n", fieldName(field.option), name)
			}
		}
	} else {
		fmt.Fprintf(out, "// Deserialize replaces fields from a complete binary message.\nfunc (d *%s) Deserialize(r io.Reader) error {\n", decl.name)
	}

	// Encode or decode each field in wire order, excluding declaration constants.
	for _, field := range decl.fields {
		if field.flag == "const" {
			continue
		}
		name := fieldName(field.name)
		if field.flag == "proto" {
			if writing {
				fmt.Fprintf(out, "if n, err := w.Write(%sBytes); err != nil { return err } else if n != len(%sBytes) { return io.ErrShortWrite }\n\n", name, name)
			} else {
				fmt.Fprintf(out, "%sBytes, err := readProtoBufHeaderBytes(r, d.%s)\nif err != nil { return err }\n", name, fieldName(field.option))
				fmt.Fprintf(out, "d.%s = new(%s)\nif err := d.%s.UnmarshalVT(%sBytes); err != nil { return err }\n\n", name, languageType(field.typ), name, name)
			}
			continue
		}

		// Fixed buffers must occupy their exact wire width, even on zero-value reads.
		if field.option != "" {
			size, err := strconv.ParseUint(field.option, 10, 31)
			if err != nil || size == 0 {
				return fmt.Errorf("%s.%s: invalid fixed array size %q", decl.name, name, field.option)
			}
			if writing {
				fmt.Fprintf(out, "if len(d.%s) != %d { return errors.New(%q) }\n", name, size, decl.name+"."+name+": invalid fixed array length")
			} else {
				fmt.Fprintf(out, "d.%s = make(%s, %d)\n", name, fieldType(field), size)
			}
		}

		// Scalar codecs retain the declared width and strip only the protobuf marker.
		if writing {
			value := "d." + name
			if field.flag == "protomask" || field.flag == "protomaskgc" {
				value = "uint32(" + value + ") | ProtoMask"
			}
			fmt.Fprintf(out, "if err := binary.Write(w, binary.LittleEndian, %s); err != nil { return err }\n\n", value)
		} else {
			value := "&d." + name
			if field.option != "" {
				value = "d." + name
			}
			fmt.Fprintf(out, "if err := binary.Read(r, binary.LittleEndian, %s); err != nil { return err }\n", value)
			if field.flag == "protomask" || field.flag == "protomaskgc" {
				fmt.Fprintf(out, "d.%s = %s(uint32(d.%s) & EMsgMask)\n", name, languageType(field.typ), name)
			}
			out.WriteByte('\n')
		}
	}
	out.WriteString("return nil\n}\n\n")
	return nil
}
